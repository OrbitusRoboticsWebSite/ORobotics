import fs from 'node:fs/promises';
import { ArmClearancePreview } from '../assets/js/rob-arm-clearance.mjs';
import { ARM_CENTERED_LIMIT } from '../assets/js/rob-gesture-core.mjs';

const document=JSON.parse(await fs.readFile('static/models/rob/gesture-studio/rob-scan-rig.json','utf8'));
const planner=new ArmClearancePreview(document);
// The previous reviewed overhead configuration is a redundancy seed, not a
// destination or a shifted zero. IK refines it under centered travel/clearance.
let seed={neck_pan:6,...Object.fromEntries([-7.4,56.8,15.6,-89,.4,35.6,0].map((v,i)=>['left_joint'+(i+1),v]))};
const waypoints=[];
for(const y of [.42,.46,.38,.46,.38,.42]) {
  const target=[.10,y,1.42],solution=planner.solveIK({side:'left',target,seed});
  seed=solution.offsets;waypoints.push({target,...solution});
}
const poses=[{},...waypoints.map(w=>w.offsets),{}],times=[0];
for(let i=1;i<poses.length;i++) {
  const delta=Math.max(...Object.keys(seed).map(n=>Math.abs((poses[i][n]||0)-(poses[i-1][n]||0))));
  const seconds=Math.max(i===1||i===poses.length-1?12:2,1.875*delta/15,Math.sqrt(5.774*delta/45));
  times.push(times.at(-1)+Math.ceil(seconds*2)/2);
}
const clip={schemaVersion:1,simulationOnly:true,kind:'gesture',name:'A small hello',duration:times.at(-1),
  tracks:Object.fromEntries(Object.keys(seed).map(n=>[n,poses.map((p,i)=>[times[i],p[n]||0])]))};
const sweep=planner.validateMotion(clip);
const report={algorithm:'position-only damped least-squares IK with centered bounds and head-clearance rejection',
  centeredLimitDegrees:ARM_CENTERED_LIMIT,sourceProfileSHA256:document.provenance.profileSHA256,
  waypoints:waypoints.map((w,i)=>({time:times[i+1],targetMeters:w.target,errorMeters:w.errorMeters,iterations:w.iterations})),...sweep};
await fs.writeFile('assets/js/rob-hello-plan.mjs','// Generated by scripts/plan-rob-hello.mjs; simulation only.\nexport const HELLO_GESTURE = '+JSON.stringify(clip,null,2)+';\nexport const HELLO_PLANNING = '+JSON.stringify(report,null,2)+';\n');
console.log(JSON.stringify({duration:clip.duration,...report},null,2));
